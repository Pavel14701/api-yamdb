"""Утилиты для работы с кодом подтверждения пользователя."""

import hashlib
import uuid


def generate_confirmation_code() -> str:
    """Генерирует случайный код подтверждения для пользователя.

    Возвращает hex-строку на основе uuid4 — код непредсказуем
    и безопасен для отправки по email.
    """
    return uuid.uuid4().hex


def hash_confirmation_code(code: str) -> str:
    """Возвращает sha256-хэш кода подтверждения.

    В базе хранится только хэш, чтобы исходный код нельзя было
    получить даже при утечке данных. Проверка кода выполняется
    сравнением хэша введённого кода с сохранённым хэшем.
    """
    return hashlib.sha256(code.encode('utf-8')).hexdigest()
